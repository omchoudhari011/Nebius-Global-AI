def _cmd_run_task(args: argparse.Namespace) -> int:
    from . import conversations, scheduler, tasks

    user_id = _bootstrap()
    match = next((t for t in tasks.list_tasks(user_id) if t["name"] == args.name), None)
    if match is None:
        print(f"No task called {args.name!r}.", file=sys.stderr)
        return 1
    run_id = scheduler.run_task(match["id"])
    if run_id is None:
        print("That task is already running.", file=sys.stderr)
        return 1
    run = tasks.get_run(user_id, run_id)
    print(f"Run {run_id}: {run['status']}" + (f" - {run['error']}" if run["error"] else ""))
    if run["conversation_id"]:
        convo = conversations.get_conversation(user_id, run["conversation_id"]) or {"messages": []}
        for message in convo["messages"]:
            if message["role"] == "assistant":
                print("\n" + message["content"])
    return 0 if run["status"] == "succeeded" else 1


def _cmd_rotate_keys(_: argparse.Namespace) -> int:
    from . import db
    from .crypto import rotate

    db.init_db()
    counts: dict[str, int] = {}
    with db.connect() as conn:
        for table, column in (
            ("messages", "content"),
            ("messages", "checks"),
            ("tool_calls", "args"),
            ("tool_calls", "result"),
            ("memory_vectors", "vector"),
            ("message_vectors", "vector"),
        ):
            rows = conn.execute(f"SELECT id, {column} AS blob FROM {table} WHERE {column} IS NOT NULL").fetchall()
            for row in rows:
                conn.execute(f"UPDATE {table} SET {column} = ? WHERE id = ?", (rotate(row["blob"]), row["id"]))
            counts[f"{table}.{column}"] = len(rows)
        rows = conn.execute("SELECT id, content, updated_at FROM memories").fetchall()
        for row in rows:
            conn.execute("UPDATE memories SET content = ? WHERE id = ?", (rotate(row["content"]), row["id"]))
            # memories_touch bumps updated_at on a content change, but re-encrypting isn't an edit.
            conn.execute("UPDATE memories SET updated_at = ? WHERE id = ?", (row["updated_at"], row["id"]))
        counts["memories.content"] = len(rows)
    print(json.dumps({"re-encrypted": counts}, indent=2))
    return 0


def _cmd_backup(args: argparse.Namespace) -> int:
    """Consistent copies of every database (safe while the server runs), via SQLite's backup API."""
    import sqlite3
    from datetime import datetime, timezone

    from .config import get_settings

    settings = get_settings()
    target = Path(args.dest) / datetime.now(timezone.utc).strftime("custodian-%Y%m%dT%H%M%SZ")
    target.mkdir(parents=True, exist_ok=False)
    sources = [(settings.database_path, target / "custodian.db")]
    for path in sorted(settings.tool_data_dir.glob("*/*.db")):
        sources.append((path, target / "tools" / path.parent.name / path.name))
    for source, dest in sources:
        dest.parent.mkdir(parents=True, exist_ok=True)
        src, dst = sqlite3.connect(source), sqlite3.connect(dest)
        try:
            src.backup(dst)
        finally:
            src.close()
            dst.close()
        print(f"backed up {source} -> {dest}")
    print("Done. Keep APP_SECRET_KEY with the backup: without it the encrypted text can't be read.")
    return 0


def _cmd_sandbox_selftest(_: argparse.Namespace) -> int:
    from .tools.base import ToolFailure, ToolRequest, ToolTimeout
    from .tools.sandbox import SubprocessSandbox

    sandbox = SubprocessSandbox()
    with tempfile.TemporaryDirectory() as tmp:
        ctx = {"user_id": 0, "data_dir": str(Path(tmp) / "probe"), "timezone": "UTC"}
        outside = str(BACKEND_DIR / "schema.sql")
        probes = [
            ("network is blocked", "try_network", {}, False),
            ("reading app files outside the data dir is blocked", "try_read_file", {"path": outside}, False),
            ("writing outside the data dir is blocked", "try_write_file", {"path": str(Path(tmp) / "x.txt")}, False),
            ("starting processes is blocked", "try_subprocess", {}, False),
            ("writing inside the data dir works", "write_inside", {}, True),
        ]
        failures = 0
        for label, fn, fn_args, should_succeed in probes:
            try:
                sandbox.run(ToolRequest("app.tools._selftest", fn, fn_args, ctx), 10)
                ok = should_succeed
            except (ToolFailure, ToolTimeout):
                ok = not should_succeed
            failures += not ok
            print(f"{'PASS' if ok else 'FAIL'}  {label}")
        env = sandbox.run(ToolRequest("app.tools._selftest", "read_env", {}, ctx), 10)
        leaked = [k for k in env if k in ("APP_SECRET_KEY", "SESSION_SECRET", "NEBIUS_API_KEY", "CUSTODIAN_PASSCODE")]
        failures += bool(leaked)
        print(f"{'FAIL' if leaked else 'PASS'}  secrets are not visible to tools{f' (leaked: {leaked})' if leaked else ''}")
    return 1 if failures else 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m app.cli", description="Custodian operator commands")
    sub = parser.add_subparsers(dest="command", required=True)

    p = sub.add_parser("init-env", help="write backend/.env with fresh secrets")
    p.add_argument("--production", action="store_true")
    p.add_argument("--force", action="store_true")
    p.add_argument("--timezone", default="UTC")
    p.add_argument("--path", help="where to write (default backend/.env)")
    p.set_defaults(fn=_cmd_init_env)

    sub.add_parser("gen-key", help="print a new Fernet key").set_defaults(fn=_cmd_gen_key)
    sub.add_parser("check", help="validate settings and the database").set_defaults(fn=_cmd_check)

    p = sub.add_parser("seed-demo", help="add demo data")
    p.add_argument("--grant-reads", action="store_true", help="also switch on every read permission")
    p.set_defaults(fn=_cmd_seed_demo)

    p = sub.add_parser("run-task", help="run a scheduled task now")
    p.add_argument("name")
    p.set_defaults(fn=_cmd_run_task)

    sub.add_parser("rotate-keys", help="re-encrypt with the first APP_SECRET_KEY").set_defaults(fn=_cmd_rotate_keys)

    p = sub.add_parser("backup", help="copy every database into a timestamped folder")
    p.add_argument("dest", help="folder to create the backup in, e.g. /data/backups")
    p.set_defaults(fn=_cmd_backup)
    sub.add_parser("sandbox-selftest", help="check the tool sandbox").set_defaults(fn=_cmd_sandbox_selftest)

    p = sub.add_parser("export", help="write everything you have stored, decrypted, to a JSON file")
    p.add_argument("out", help="file to write, e.g. my-custodian-data.json")
    p.add_argument("--force", action="store_true")
    p.set_defaults(fn=_cmd_export)

    p = sub.add_parser("license-keygen", help="vendor: create the key that signs license keys")
    p.add_argument("--out", default="~/.custodian/license-signing-key.pem", help="where to write it (outside the repository)")
    p.set_defaults(fn=_cmd_license_keygen)

    p = sub.add_parser("license-issue", help="vendor: print a signed license key")
    p.add_argument("--signing-key", default="~/.custodian/license-signing-key.pem")
    p.add_argument("--plan", required=True, help="pro or cloud")
    p.add_argument("--to", required=True, help="the customer's name, shown on their Account screen")
    p.add_argument("--days", type=int, default=365, help="how long it's valid (default 365)")
    p.add_argument("--perpetual", action="store_true", help="no expiry")
    p.set_defaults(fn=_cmd_license_issue)

    args = parser.parse_args(argv)
    try:
        return args.fn(args)
    except ConfigError as exc:
        print(f"Configuration error: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
